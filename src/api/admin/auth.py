from __future__ import annotations

import secrets
from typing import TYPE_CHECKING, ClassVar, Literal, cast

from quart import g, request

from admin_permissions import PERMISSIONS, allows, prerequisite, validate_grants
from api.admin._base import AsyncAdminApiMixin
from api.common import Route
from api.decorators import requires_admin_auth, requires_fields_strict
from api.decorators.auth import credential_digest, permission_denied
from db.admin import AdminIdentity, AdminKind
from util import err, ok

if TYPE_CHECKING:
    from collections.abc import MutableMapping

    from api.common import ResponseType
    from config import JsonValue
    from core.services.audit import AUDIT_VALUES
    from custom_types import JsonifyValue


def public_identity(identity: AdminIdentity) -> dict[str, JsonifyValue]:
    return {
        "id": identity.id,
        "kind": identity.kind,
        "name": identity.name,
        "permissions": list(identity.permissions),
        "root": False,
    }


class AsyncAuthRoutes(AsyncAdminApiMixin):
    ROUTES: ClassVar[tuple[Route, ...]] = (
        Route("GET", "/api/auth/permissions", "auth_catalog"),
        Route("GET", "/api/auth/list", "auth_list"),
        Route("POST", "/api/auth/create", "auth_create"),
        Route("POST", "/api/auth/update", "auth_update"),
        Route("POST", "/api/auth/delete", "auth_delete"),
    )

    def _root_identity(self, kind: AdminKind) -> dict[str, JsonifyValue]:
        return {
            "id": "root",
            "kind": kind,
            "root": True,
            "permissions": ["*"],
            "name": self.cfg.view()["api_admin_ui_auth"][0] if kind == "accounts" else "root",
        }

    @requires_admin_auth
    async def auth_catalog(self) -> ResponseType:
        identity = cast(AdminIdentity | None, g.admin_identity)
        return ok(
            obj={
                "permissions": list(g.admin_permissions),
                "catalog": [
                    {"permission": permission, "requires": prerequisite(permission)}
                    for permission in PERMISSIONS
                ],
                "identity": public_identity(identity)
                if identity
                else self._root_identity("accounts" if g.admin_browser_auth else "tokens"),
            }
        )

    @requires_admin_auth
    async def auth_list(self) -> ResponseType:
        kind = request.args.get("kind")
        if not isinstance(kind, str) or kind not in {"accounts", "tokens"}:
            return err("kind must be accounts or tokens")
        kind = cast(AdminKind, kind)
        response, status = ok(
            obj={
                "items": [
                    self._root_identity(kind),
                    *(
                        public_identity(identity)
                        for identity in await self.sub.res.db.admin_identities(kind)
                    ),
                ]
            }
        )
        response.headers["Cache-Control"] = "no-store"
        return response, status

    @requires_admin_auth
    @requires_fields_strict()
    async def auth_create(self) -> ResponseType:
        return await self._auth_save(create=True)

    @requires_admin_auth
    @requires_fields_strict()
    async def auth_update(self) -> ResponseType:
        return await self._auth_save(create=False)

    async def _auth_save(self, *, create: bool) -> ResponseType:
        body = cast(dict[str, object], g.json_obj)
        if body.keys() - {"id", "kind", "name", "permissions", "password", "rotate"}:
            return err("Unsupported fields")
        kind = body.get("kind")
        if not isinstance(kind, str) or kind not in {"accounts", "tokens"}:
            return err("kind must be accounts or tokens")
        kind = cast(AdminKind, kind)
        identity_id = body.get("id")
        existing: AdminIdentity | None = None
        if create:
            if "id" in body:
                return err("id is generated by the server")
        else:
            if not isinstance(identity_id, str):
                return err("id must be a string")
            if identity_id == "root":
                return await self._auth_update_root(kind, body)
            existing = await self.sub.res.db.admin_identity(identity_id)
            if existing is None or existing.kind != kind:
                return err("Admin identity not found", 404)
            for grant in existing.permissions:
                if not allows(g.admin_permissions, grant):
                    return permission_denied(grant)
        name = body.get("name", existing.name if existing else None)
        if (
            not isinstance(name, str)
            or not 1 <= len(name) <= 64
            or name != name.strip()
            or any(ord(char) < 32 or ord(char) == 127 for char in name)
        ):
            return err(
                "name must be 1-64 characters without surrounding whitespace or control characters"
            )
        if kind == "accounts" and name == self.cfg.view()["api_admin_ui_auth"][0]:
            return err("The root account name is reserved", 409)
        try:
            permissions = validate_grants(
                body.get("permissions", list(existing.permissions) if existing else None)
            )
        except ValueError as exc:
            return err(str(exc))
        for permission in permissions:
            if not allows(g.admin_permissions, permission):
                return permission_denied(permission)
        secret = existing.secret if existing else ""
        token: str | None = None
        if kind == "accounts":
            if "rotate" in body:
                return err("rotate is only valid for tokens")
            password = body.get("password")
            if "password" in body or create:
                if not isinstance(password, str) or not 1 <= len(password) <= 128:
                    return err("password must be 1-128 characters")
                secret = await self.sub.password_svc.hash(password)
        else:
            if "password" in body or ("rotate" in body and not isinstance(body["rotate"], bool)):
                return err("tokens accept a boolean rotate, not a password")
            if create or body.get("rotate") is True:
                token = "ak." + secrets.token_urlsafe(48)
                secret = credential_digest(token)
        identity = AdminIdentity(
            existing.id if existing else secrets.token_hex(16),
            kind,
            name,
            secret,
            tuple(permissions),
            existing.revision if existing else 1,
        )
        if not await self.sub.res.db.admin_save_identity(
            identity, actor=g.admin_identity, create=create
        ):
            return err("Admin identity changed; reload and retry", 409)
        obj: dict[str, JsonifyValue] = {"item": public_identity(identity)}
        if token is not None:
            obj["token"] = token
        await self._audit_auth("create" if create else "update", identity.id, kind, obj)
        response, status = ok(obj=obj, code=201 if create else 200)
        response.headers["Cache-Control"] = "no-store"
        return response, status

    async def _auth_update_root(self, kind: AdminKind, body: dict[str, object]) -> ResponseType:
        if not allows(g.admin_permissions, "*"):
            return permission_denied("*")
        if "permissions" in body and body["permissions"] != ["*"]:
            return err("Root permissions must remain ['*']")
        values: dict[str, JsonValue] = {}
        token: str | None = None
        if kind == "accounts":
            if "rotate" in body:
                return err("rotate is only valid for tokens")
            configured = self.cfg.view()["api_admin_ui_auth"]
            name, password = body.get("name", configured[0]), body.get("password", configured[1])
            if not isinstance(name, str) or (
                name != configured[0]
                and (
                    not name
                    or name != name.strip()
                    or len(name) > 64
                    or any(ord(char) < 32 or ord(char) == 127 for char in name)
                )
            ):
                return err("Invalid root account name")
            if (
                not isinstance(password, str)
                or not password
                or ("password" in body and len(password) > 128)
            ):
                return err("Invalid root account password")
            if await self.sub.res.db.admin_login_identity(name) is not None:
                return err("Account name already exists", 409)
            values["api_admin_ui_auth"] = [name, password]
        else:
            if (
                "password" in body
                or body.get("name", "root") != "root"
                or ("rotate" in body and not isinstance(body["rotate"], bool))
            ):
                return err("Root token accepts only rotate and immutable root metadata")
            if body.get("rotate") is True:
                token = secrets.token_urlsafe(48)
                values["api_token"] = token

        def patch(tx: MutableMapping[str, JsonValue]) -> None:
            tx.update(values)

        if values:
            await self.cfg.mutate(patch)
            if kind == "accounts":
                await self.sub.res.db.set_admin_ui_session(None)
            await self._backup_config_after_commit()
        obj: dict[str, JsonifyValue] = {
            "item": self._root_identity(kind),
            "restart": ["api_token"] if token else [],
        }
        if token:
            obj["token"] = token
        if values:
            await self._audit_auth("update", "root", kind, obj)
        response, status = ok(obj=obj)
        response.headers["Cache-Control"] = "no-store"
        return response, status

    @requires_admin_auth
    @requires_fields_strict(("id", str), ("kind", str))
    async def auth_delete(self) -> ResponseType:
        body = g.json_obj
        if body.keys() - {"id", "kind"} or body["kind"] not in {"accounts", "tokens"}:
            return err("Expected id and kind (accounts or tokens)")
        if body["id"] == "root":
            return err("Root identities cannot be deleted", 403, {"root": True})
        identity = await self.sub.res.db.admin_identity(body["id"])
        if identity is None or identity.kind != body["kind"]:
            return err("Admin identity not found", 404)
        for permission in identity.permissions:
            if not allows(g.admin_permissions, permission):
                return permission_denied(permission)
        if not await self.sub.res.db.admin_delete_identity(identity, actor=g.admin_identity):
            return err("Admin identity changed; reload and retry", 409)
        await self._audit_auth("delete", identity.id, identity.kind)
        return ok(obj={"id": identity.id, "kind": identity.kind})

    async def _audit_auth(
        self,
        action: Literal["create", "update", "delete"],
        identity_id: str,
        kind: AdminKind,
        result: JsonifyValue = None,
    ) -> None:
        actor = cast(AdminIdentity | None, g.admin_identity)
        name: AUDIT_VALUES = (
            "admin_auth_create"
            if action == "create"
            else "admin_auth_delete"
            if action == "delete"
            else "admin_auth_update"
        )
        await self.sub.audit_svc.audit_committed(
            name=name,
            info={"id": identity_id, "kind": kind, "actor": actor.id if actor else "root"},
            result=result,
        )
