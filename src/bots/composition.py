"""Explicit typing contracts for the bot mixin composition points."""

from __future__ import annotations

from typing import TYPE_CHECKING, Unpack

__all__ = ["AdminFeatureMixin", "PublicFeatureMixin"]


if TYPE_CHECKING:
    from collections.abc import MutableMapping

    from telebot import types
    from telebot.async_telebot import AsyncTeleBot

    from config import AppConfig, LangConfig
    from core import AsyncSubscription
    from core.async_common import Snapshot
    from loggers import Logger

    from .common import MessageOptions
    from .handler_backend import Step

    class AdminFeatureMixin:
        bot: AsyncTeleBot
        log: Logger
        cfg: Snapshot[AppConfig]
        lang_cfg: Snapshot[LangConfig]
        sub: AsyncSubscription
        USERS_PER_PAGE: int
        admin_uids: list[int]
        _pending_codes: MutableMapping[str | int, str]
        _pending_edits: MutableMapping[str | int, dict[str, str]]
        _pagination_state: MutableMapping[str | int, dict[str, int]]
        _pending_leaderboard: MutableMapping[str | int, dict[str, str | int]]

        def is_admin(self, user_id: int) -> bool: ...
        def _expect(self, message: types.Message, step: Step, *arguments: object) -> None: ...
        def _clear_steps(self, chat_id: int) -> None: ...
        def _clear_pending(self, chat_id: int) -> None: ...
        async def _answer_callback(self, call_id: str, text: str | None = None) -> None: ...
        async def _send_message(
            self, chat_id: int, text: str, **kwargs: Unpack[MessageOptions],
        ) -> None: ...
        async def _delete_message(
            self, chat_id: int, message_id: int, *, secret: bool = False,
        ) -> None: ...
        def get_main_menu(self) -> types.InlineKeyboardMarkup: ...
        def get_codes_menu(self) -> types.InlineKeyboardMarkup: ...
        async def get_users_menu(self, prefix: str, page: int = 0) -> types.InlineKeyboardMarkup: ...
        async def _cb_online_users(self, chat_id: int) -> None: ...
        async def _cb_list_users(self, chat_id: int, page: int = 0) -> None: ...
        async def _cb_refresh(self, chat_id: int) -> None: ...
        async def _step_reset_user(self, message: types.Message) -> None: ...
        async def _step_add_user_name(self, message: types.Message) -> None: ...
        async def _cb_info_user(self, chat_id: int, username: str) -> None: ...
        async def _cb_del_user(self, chat_id: int, username: str) -> None: ...
        async def _cb_list_codes(self, chat_id: int) -> None: ...
        async def _step_info_code(self, message: types.Message) -> None: ...
        async def _step_del_code(self, message: types.Message) -> None: ...
        async def _step_add_code_name(self, message: types.Message) -> None: ...
        async def _cb_all_panels_status(self, chat_id: int) -> None: ...
        async def _step_add_code_days(
            self, message: types.Message, code_type: str, code_name: str,
        ) -> None: ...
        async def _step_chart_username(self, message: types.Message) -> None: ...
        async def _cb_leaderboard_type(self, chat_id: int) -> None: ...
        async def _cb_edit_user_options(self, chat_id: int, username: str) -> None: ...
        async def _cb_edit_fingerprint(self, chat_id: int, username: str) -> None: ...
        async def _cb_edit_limit(self, chat_id: int, username: str) -> None: ...
        async def _cb_edit_wl_limit(self, chat_id: int, username: str) -> None: ...
        async def _cb_edit_time(self, chat_id: int, username: str) -> None: ...
        async def _cb_edit_name(self, chat_id: int, username: str) -> None: ...
        async def _cb_leaderboard_order(self, chat_id: int) -> None: ...
        async def _cb_leaderboard_window(self, chat_id: int) -> None: ...

    class PublicFeatureMixin:
        bot: AsyncTeleBot
        log: Logger
        cfg: Snapshot[AppConfig]
        lang_cfg: Snapshot[LangConfig]
        sub: AsyncSubscription
        TEXTS: dict[str, dict[str, str]]

        def _expect(self, message: types.Message, step: Step, *arguments: object) -> None: ...
        def _clear_steps(self, chat_id: int) -> None: ...

        async def _answer_callback(self, call_id: str, text: str | None = None) -> None: ...
        async def _send_message(
            self, chat_id: int, text: str, **kwargs: Unpack[MessageOptions],
        ) -> None: ...
        async def _delete_message(
            self, chat_id: int, message_id: int, *, secret: bool = False,
        ) -> None: ...
        async def get_lang(self, uid: int) -> str: ...
        async def get_menu(self, uid: int) -> types.ReplyKeyboardMarkup: ...
        async def cmd_start(self, message: types.Message) -> None: ...
        async def send_info(self, chat_id: int, uid: int, lang: str) -> None: ...
        async def send_link(self, chat_id: int, uid: int, lang: str) -> None: ...
        async def step_bonus(self, message: types.Message) -> None: ...
        async def step_reset(self, message: types.Message) -> None: ...
        async def step_delete(self, message: types.Message) -> None: ...
        async def settings_callback(self, call: types.CallbackQuery) -> None: ...
        async def fp_callback(self, call: types.CallbackQuery) -> None: ...
        async def login_callback(self, call: types.CallbackQuery) -> None: ...
        async def chart_callback(self, call: types.CallbackQuery) -> None: ...
else:

    class AdminFeatureMixin:
        """Runtime-neutral base for administrator feature mixins."""

    class PublicFeatureMixin:
        """Runtime-neutral base for public feature mixins."""
